function validateOrderForm() {
  let isValid = true;

  const nameInput = document.getElementById("customer-name");
  const phoneInput = document.getElementById("customer-phone");
  const addressInput = document.getElementById("customer-address");

  const nameError = document.getElementById("name-error");
  const phoneError = document.getElementById("phone-error");
  const addressError = document.getElementById("address-error");

  // Ism tekshiruvi
  if (nameInput.value.trim().length < 3) {
    nameError.textContent = "Iltimos, ism va familiyangizni to'liq kiriting (kamida 3 ta harf).";
    nameInput.classList.add("invalid");
    isValid = false;
  } else {
    nameError.textContent = "";
    nameInput.classList.remove("invalid");
  }

  // Telefon tekshiruvi (kamida 9 ta raqam)
  const digitsOnly = phoneInput.value.replace(/\D/g, "");
  if (digitsOnly.length < 9) {
    phoneError.textContent = "To'g'ri telefon raqamini kiriting (masalan: +998 90 123 45 67).";
    phoneInput.classList.add("invalid");
    isValid = false;
  } else {
    phoneError.textContent = "";
    phoneInput.classList.remove("invalid");
  }

  // Manzil tekshiruvi
  if (addressInput.value.trim().length < 5) {
    addressError.textContent = "Yetkazib berish manzilini aniqroq kiriting.";
    addressInput.classList.add("invalid");
    isValid = false;
  } else {
    addressError.textContent = "";
    addressInput.classList.remove("invalid");
  }

  return isValid;
}

