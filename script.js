/* =========================================================
   6. SAVATCHA (CART) TIZIMI
========================================================= */
function addToCart(productId) {
  const product = ALL_PRODUCTS.find((p) => p.id === productId);
  if (!product) return;

  const existingItem = cart.find((item) => item.id === productId);
  if (existingItem) {
    existingItem.quantity += 1;
  } else {
    cart.push({
      id: product.id,
      name: product.name,
      price: product.price,
      image: product.image,
      quantity: 1
    });
  }

  saveCart();
  updateCartUI();
  showToast(`"${product.name}" savatchaga qo'shildi!`);
}

function changeQuantity(productId, delta) {
  const index = cart.findIndex((item) => item.id === productId);
  if (index === -1) return;

  cart[index].quantity += delta;
  if (cart[index].quantity <= 0) {
    cart.splice(index, 1);
  }

  saveCart();
  updateCartUI();
}

function removeFromCart(productId) {
  cart = cart.filter((item) => item.id !== productId);
  saveCart();
  updateCartUI();
  showToast("Mahsulot savatchadan o'chirildi");
}

function getCartTotal() {
  return cart.reduce((sum, item) => sum + item.price * item.quantity, 0);
}

function getCartCount() {
  return cart.reduce((sum, item) => sum + item.quantity, 0);
}

function updateCartUI() {
  const totalCount = getCartCount();
  const totalAmount = getCartTotal();

  cartBadgeEl.textContent = totalCount;
  cartTotalPriceEl.textContent = formatPrice(totalAmount);
  modalTotalAmountEl.textContent = formatPrice(totalAmount);

  if (cart.length === 0) {
    cartFooterEl.style.display = "none";
    cartItemsContainerEl.innerHTML = `
      <div class="cart-empty">
        <div class="cart-empty-icon">🛒</div>
        <h4>Savatchangiz hozircha bo'sh</h4>
        <p>Menyudan mazali taomlarni tanlab savatchaga qo'shing!</p>
      </div>
    `;
    return;
  }

  cartFooterEl.style.display = "block";
  cartItemsContainerEl.innerHTML = cart
    .map(
      (item) => `
      <div class="cart-item">
        <img src="${item.image}" alt="${item.name}" class="cart-item-img" />
        <div class="cart-item-info">
          <div class="cart-item-title">${item.name}</div>
          <div class="cart-item-price">${formatPrice(item.price * item.quantity)}</div>
          <div class="cart-qty-controls">
            <button class="qty-btn" onclick="changeQuantity(${item.id}, -1)" aria-label="Kamaytirish">−</button>
            <span>${item.quantity}</span>
            <button class="qty-btn" onclick="changeQuantity(${item.id}, 1)" aria-label="Oshirish">+</button>
          </div>
        </div>
        <button class="remove-item-btn" onclick="removeFromCart(${item.id})" title="O'chirish">🗑️</button>
      </div>
    `
    )
    .join("");
}

